// Test_FullAssetSuite_ProtobufWithCEL tests Protobuf code generation with CEL validation constraints.
// CEL (Common Expression Language) validation is used to emit bufbuild/protovalidate constraints
// for YANG types with restrictions (range, length, pattern, etc.).
func Test_FullAssetSuite_ProtobufWithCEL(t *testing.T) {
	assetDir := filepath.Join("..", "assets")
	_, err := os.Stat(assetDir)
	if os.IsNotExist(err) {
		t.Skip("assets directory not found, skipping CEL test")
	}

	yangFiles, err := filepath.Glob(filepath.Join(assetDir, "*.yang"))
	require.NoError(t, err)
	require.NotEmpty(t, yangFiles)

	// Sort files for deterministic test execution
	sort.Strings(yangFiles)

	var astModules []*gotya.ASTModule
	for _, yangFile := range yangFiles {
		astMod, err := gotya.ParseFile(yangFile)
		if err != nil || astMod.Keyword() == "submodule" {
			continue
		}
		astModules = append(astModules, astMod)
	}
	require.NotEmpty(t, astModules, "no YANG modules parsed successfully")

	schemaModules := convertToSchemaModules(t, astModules, assetDir)
	require.NotEmpty(t, schemaModules, "no schema modules compiled")

	// Test Protobuf generation with CEL validation enabled
	opts := &protobuf.Options{
		PackageName:           "ygot_cel",
		RootName:              "Device",
		GenerateFakeroot:      true,
		GenerateCELValidation: true,
	}

	gen := protobuf.New(opts)
	var buf bytes.Buffer
	err = gen.GenerateDevice(schemaModules, &buf)
	require.NoError(t, err, "Protobuf+CEL generation must not fail with asset suite")

	output := buf.String()
	require.NotEmpty(t, output, "GenerateDevice with CEL must produce output")

	// Verify protobuf structure with CEL
	assert.Contains(t, output, "syntax = \"proto3\";")
	assert.Contains(t, output, "package "+opts.PackageName)
	assert.Contains(t, output, "// Code generated by gotya")

	// Verify CEL import is present when GenerateCELValidation is enabled
	assert.Contains(t, output, "import \"buf/validate/validate.proto\";",
		"CEL validation requires bufbuild/protovalidate import")

	// Verify field numbers are valid
	verifyProtobufFieldNumbers(t, output)

	t.Logf("Generated %d bytes of Protobuf+CEL code", len(output))
}

// Test_FullAssetSuite_ProtobufCELVsNoCEL tests that CEL validation option produces different output.
// With CEL enabled, leaf/leaflist fields with constraints should have validate options.
func Test_FullAssetSuite_ProtobufCELVsNoCEL(t *testing.T) {
	assetDir := filepath.Join("..", "assets")
	_, err := os.Stat(assetDir)
	if os.IsNotExist(err) {
		t.Skip("assets directory not found")
	}

	yangFiles, err := filepath.Glob(filepath.Join(assetDir, "*.yang"))
	require.NoError(t, err)
	require.NotEmpty(t, yangFiles)

	// Sort for determinism
	sort.Strings(yangFiles)

	var astModules []*gotya.ASTModule
	for _, yangFile := range yangFiles {
		astMod, err := gotya.ParseFile(yangFile)
		if err != nil || astMod.Keyword() == "submodule" {
			continue
		}
		astModules = append(astModules, astMod)
	}
	require.NotEmpty(t, astModules)

	schemaModules := convertToSchemaModules(t, astModules, assetDir)
	require.NotEmpty(t, schemaModules)

	// Generate without CEL
	noCELOpts := &protobuf.Options{
		PackageName:      "ygot_no_cel",
		GenerateFakeroot: true,
	}
	noCELGen := protobuf.New(noCELOpts)
	var noCELBuf bytes.Buffer
	err = noCELGen.GenerateDevice(schemaModules, &noCELBuf)
	require.NoError(t, err)

	noCELOutput := noCELBuf.String()

	// Generate with CEL
	celOpts := &protobuf.Options{
		PackageName:           "ygot_with_cel",
		GenerateFakeroot:      true,
		GenerateCELValidation: true,
	}
	celGen := protobuf.New(celOpts)
	var celBuf bytes.Buffer
	err = celGen.GenerateDevice(schemaModules, &celBuf)
	require.NoError(t, err)

	celOutput := celBuf.String()

	// Verify CEL output has the validation import
	assert.Contains(t, celOutput, "import \"buf/validate/validate.proto\";",
		"CEL output must import buf/validate/validate.proto")
	assert.NotContains(t, noCELOutput, "import \"buf/validate/validate.proto\";",
		"non-CEL output must not import buf/validate/validate.proto")

	// Verify lengths are different (CEL has validation constraints)
	require.NotEqual(t, len(noCELOutput), len(celOutput),
		"CEL and non-CEL outputs must differ in size due to validation constraints")

	t.Logf("Without CEL: %d bytes; With CEL: %d bytes (delta: %d)",
		len(noCELOutput), len(celOutput), len(celOutput)-len(noCELOutput))
}

