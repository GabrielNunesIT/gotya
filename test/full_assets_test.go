// Test_FullAssetSuite_GoGeneration tests Go code generation with the full YANG asset suite.
// This test loads all available YANG files from the assets directory and generates Go code,
// validating that the output is syntactically correct and contains expected code structures.
func Test_FullAssetSuite_GoGeneration(t *testing.T) {
	assetDir := filepath.Join("..", "assets")
	_, err := os.Stat(assetDir)
	if os.IsNotExist(err) {
		t.Skip("assets directory not found, skipping full suite test")
	}

	// Load all YANG modules from assets
	yangFiles, err := filepath.Glob(filepath.Join(assetDir, "*.yang"))
	require.NoError(t, err, "failed to glob YANG files")
	require.NotEmpty(t, yangFiles, "no YANG files found in assets directory")
	
	// Sort files for deterministic test execution
	sort.Strings(yangFiles)

	t.Logf("Found %d YANG files to process", len(yangFiles))

	// Parse all YANG files
	var astModules []*gotya.ASTModule
	var successfulParsing []string
	var failedParsing []string

	for _, yangFile := range yangFiles {
		moduleName := filepath.Base(yangFile)
		astMod, err := gotya.ParseFile(yangFile)
		if err != nil {
			failedParsing = append(failedParsing, fmt.Sprintf("%s: %v", moduleName, err))
			continue
		}
		if astMod.Keyword() == "submodule" {
			// Skip submodules, they're handled via include
			continue
		}
		astModules = append(astModules, astMod)
		successfulParsing = append(successfulParsing, moduleName)
	}

	if len(failedParsing) > 0 {
		t.Logf("Failed to parse %d modules:\n%s", len(failedParsing), strings.Join(failedParsing, "\n"))
	}
	require.NotEmpty(t, astModules, "no YANG modules parsed successfully")
	t.Logf("Successfully parsed %d modules", len(astModules))

	// Test various generator options
	testCases := []struct {
		name    string
		options *golang.Options
	}{
		{
			name:    "Basic generation",
			options: &golang.Options{PackageName: "device"},
		},
		{
			name: "With fakeroot",
			options: &golang.Options{
				PackageName:      "device",
				GenerateFakeroot: true,
				RootName:         "Root",
			},
		},
		{
			name: "With getters and setters",
			options: &golang.Options{
				PackageName:      "device",
				GenerateGetters:  true,
				GenerateSetters:  true,
				GenerateFakeroot: true,
			},
		},
		{
			name: "Skip deprecated and obsolete",
			options: &golang.Options{
				PackageName:     "device",
				SkipDeprecated:  true,
				SkipObsolete:    true,
				GenerateFakeroot: true,
			},
		},
		{
			name: "With annotations and methods",
			options: &golang.Options{
				PackageName:              "device",
				AddAnnotations:           true,
				GeneratePopulateDefault:  true,
				GenerateOrderedMaps:      true,
				GenerateFakeroot:         true,
			},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			gen := golang.New(tc.options)
			var buf bytes.Buffer

			// Test GenerateDevice with all modules
			err := gen.GenerateDevice(convertToSchemaModules(t, astModules, assetDir), &buf)
			require.NoError(t, err, "GenerateDevice failed")

			output := buf.String()
			require.NotEmpty(t, output, "GenerateDevice produced empty output")

			// Verify output can be formatted
			formatted, err := format.Source(buf.Bytes())
			require.NoError(t, err, "generated Go code is not syntactically valid")

			// Verify expected content
			assert.Contains(t, output, "package "+tc.options.PackageName)
			assert.Contains(t, output, "// Code generated by gotya")

			// Spot-check for struct definitions
			if tc.options.GenerateFakeroot {
				assert.Contains(t, output, "type "+tc.options.RootName+"Config struct", "missing root Config struct")
				assert.Contains(t, output, "type "+tc.options.RootName+"State struct", "missing root State struct")
			}

			t.Logf("Generated %d bytes of Go code (%d formatted)", len(output), len(formatted))
		})
	}
}

// Test_FullAssetSuite_ProtobufGeneration tests Protobuf code generation with the full YANG asset suite.
