// Helper functions

// assetLoader loads YANG modules from an asset directory with dependency resolution
type assetLoader struct {
	dir         string
	astCache    map[string]*ast.Module
	schemaCache map[string]*schema.Module
}

// newAssetLoader creates a new asset loader for a given directory
func newAssetLoader(dir string) *assetLoader {
	return &assetLoader{
		dir:         dir,
		astCache:    make(map[string]*ast.Module),
		schemaCache: make(map[string]*schema.Module),
	}
}

// Load compiles a module from the asset directory with dependency resolution
func (l *assetLoader) Load(name string) (*schema.Module, error) {
	if m, ok := l.schemaCache[name]; ok {
		return m, nil
	}

	astMod, err := l.LoadAST(name)
	if err != nil {
		return nil, err
	}

	comp := compiler.New(&compiler.Options{Loader: l})
	schemaMod, err := comp.Compile(astMod)

	if schemaMod != nil && err == nil {
		l.schemaCache[name] = schemaMod
		if schemaMod.Name != name && schemaMod.Name != "" {
			l.schemaCache[schemaMod.Name] = schemaMod
		}
	}

	if err != nil {
		return schemaMod, err
	}

	return schemaMod, nil
}

// LoadAST loads and parses a YANG module from the asset directory
func (l *assetLoader) LoadAST(name string) (*ast.Module, error) {
	if m, ok := l.astCache[name]; ok {
		return m, nil
	}

	files, err := os.ReadDir(l.dir)
	if err != nil {
		return nil, err
	}

	var targetPath string
	for _, f := range files {
		if strings.HasPrefix(f.Name(), name+".yang") || strings.HasPrefix(f.Name(), name+"@") {
			targetPath = filepath.Join(l.dir, f.Name())
			break
		}
	}

	if targetPath == "" {
		return nil, fmt.Errorf("module %s not found in %s", name, l.dir)
	}

	content, err := os.ReadFile(targetPath)
	if err != nil {
		return nil, err
	}

	lex := lexer.New(string(content))
	p := parser.New(lex)
	astMod := p.ParseModule()
	if astMod == nil {
		return nil, fmt.Errorf("failed to parse module AST for %s", name)
	}

	l.astCache[name] = astMod
	if astMod.Argument() != name {
		l.astCache[astMod.Argument()] = astMod
	}

	return astMod, nil
}

// Helper functions

func convertToSchemaModules(t *testing.T, astModules []*gotya.ASTModule, assetDir string) []*schema.Module {
	// Create a proper loader that can resolve cross-module dependencies from the asset directory
	loader := newAssetLoader(assetDir)

	var schemaModules []*schema.Module
	for _, astMod := range astModules {
		modName := astMod.Name()
		schemaMod, err := loader.Load(modName)
		if err != nil {
			t.Logf("Warning: failed to compile module %s: %v (will skip)", modName, err)
			continue
		}
		schemaModules = append(schemaModules, schemaMod)
	}
	return schemaModules
}

// verifyProtobufFieldNumbers checks that protobuf field numbers are sequential and non-duplicated within each message.
func verifyProtobufFieldNumbers(t *testing.T, proto string) {
	lines := strings.Split(proto, "\n")
	var currentMessage string
	var fieldNumbers map[string]map[int]bool = make(map[string]map[int]bool)

	for _, line := range lines {
		line = strings.TrimSpace(line)

		// Track current message
		if strings.HasPrefix(line, "message ") {
			parts := strings.Fields(line)
			if len(parts) >= 2 {
				currentMessage = parts[1]
				fieldNumbers[currentMessage] = make(map[int]bool)
			}
			continue
		}

		// Extract field number
		if currentMessage != "" && strings.Contains(line, " = ") {
			// Parse field definition: "type field_name = number [options];"
			parts := strings.Split(line, " = ")
			if len(parts) >= 2 {
				numPart := strings.FieldsFunc(parts[1], func(r rune) bool { return r == ';' || r == '[' || r == ' ' })
				if len(numPart) > 0 {
					var fieldNum int
					_, _ = fmt.Sscanf(numPart[0], "%d", &fieldNum)
					if fieldNum > 0 {
						if fieldNumbers[currentMessage][fieldNum] {
							t.Errorf("Duplicate field number %d in message %s", fieldNum, currentMessage)
						}
						fieldNumbers[currentMessage][fieldNum] = true
					}
				}
			}
		}

		// End of message
		if line == "}" {
			currentMessage = ""
		}
	}

	// Report findings
	for msg, nums := range fieldNumbers {
		if len(nums) > 0 {
			t.Logf("Message %s: %d fields with numbers %d to %d", msg, len(nums), findMin(nums), findMax(nums))
		}
	}
}

func findMin(m map[int]bool) int {
	min := int(^uint(0) >> 1)
	for k := range m {
		if k < min {
			min = k
		}
	}
	return min
}

func findMax(m map[int]bool) int {
	max := 0
	for k := range m {
		if k > max {
			max = k
		}
	}
	return max
}
