// Package golang provides the generator implementation for emitting Go source files.
package golang

import (
	"bytes"
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/gotya/gotya/generator"
	"github.com/gotya/gotya/schema"
)

// Options holds configuration for the Go generator.
type Options struct {
	PackageName             string
	RootName                string
	GenerateFakeroot        bool
	SkipDeprecated          bool
	SkipObsolete            bool
	AddAnnotations          bool
	GenerateGetters         bool
	GenerateSetters         bool
	GeneratePopulateDefault bool
	GenerateOrderedMaps     bool
}

// GoGenerator implements the generator.Generator interface for Go struct generation.
type GoGenerator struct {
	Options *Options
}

// New creates a new GoGenerator instance.
func New(opts *Options) generator.Generator {
	if opts == nil {
		opts = &Options{}
	}
	if opts.PackageName == "" {
		opts.PackageName = "ygot" // default
	}
	if opts.RootName == "" {
		opts.RootName = "Device" // default
	}
	return &GoGenerator{
		Options: opts,
	}
}

// Generate writes Go source code for the parsed module to the provided writer.
func (g *GoGenerator) Generate(mod *schema.Module, w io.Writer) error {
	if _, err := fmt.Fprintf(w, "// Code generated by gotya. DO NOT EDIT.\npackage %s\n\n", g.Options.PackageName); err != nil {
		return fmt.Errorf("failed to write package header: %w", err)
	}

	visited := make(map[string]bool)
	prefix := toCamelCaseTitle(mod.Name)
	for _, node := range mod.Nodes {
		if err := g.generateNode(node, w, visited, prefix, "", mod.Namespace, false); err != nil {
			return err
		}
	}
	return nil
}

// hasValidNodes checks if a node contains any data that should be exported taking into account its config flag.
func (g *GoGenerator) hasValidNodes(node schema.Node, configOnly bool) bool {
	if configOnly && !node.Config() {
		return false
	}
	base := node.GetBase()
	if g.Options.SkipDeprecated && base.Status != nil && *base.Status == "deprecated" {
		return false
	}
	if g.Options.SkipObsolete && base.Status != nil && *base.Status == "obsolete" {
		return false
	}

	switch n := node.(type) {
	case *schema.Leaf, *schema.LeafList, *schema.AnyXML, *schema.AnyData:
		return true
	case *schema.Container:
		for _, child := range getFlatDataNodes(n.Children) {
			if g.hasValidNodes(child, configOnly) {
				return true
			}
		}
	case *schema.List:
		for _, child := range getFlatDataNodes(n.Children) {
			if g.hasValidNodes(child, configOnly) {
				return true
			}
		}
	}
	return false
}

// GenerateDevice takes a list of validated YANG modules, aggregates them into a single root struct,
// encapsulating their configurations under Module-specific structs. It emits both Config and State representations.
func (g *GoGenerator) GenerateDevice(modules []*schema.Module, w io.Writer) error {
	if _, err := fmt.Fprintf(w, "// Code generated by gotya. DO NOT EDIT.\npackage %s\n\nimport (\n\t\"encoding/json\"\n\t\"encoding/xml\"\n\t\"fmt\"\n\t\"regexp\"\n\t\"sort\"\n\t\"strings\"\n\t\"unicode/utf8\"\n)\n\nvar (\n\t_ = json.Marshal\n\t_ = xml.Unmarshal\n\t_ = fmt.Errorf\n\t_ = regexp.MatchString\n\t_ = sort.SliceStable\n\t_ = strings.Join\n\t_ = utf8.RuneCountInString\n)\n\n", g.Options.PackageName); err != nil {
		return fmt.Errorf("failed to write package header: %w", err)
	}

	// visited tracks generated type names across both Config and State passes
	// to prevent duplicate struct / union-type declarations in the same file.
	visited := make(map[string]bool)

	for _, treeType := range []string{"Config", "State"} {
		configOnly := (treeType == "Config")

		if g.Options.GenerateFakeroot {
			if _, err := fmt.Fprintf(w, "// %s%s represents the aggregated YANG configuration.\n", g.Options.RootName, treeType); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
			if _, err := fmt.Fprintf(w, "type %s%s struct {\n", g.Options.RootName, treeType); err != nil {
				return fmt.Errorf("write err: %w", err)
			}

			for _, mod := range modules {
				hasValid := false
				for _, node := range mod.Nodes {
					if g.hasValidNodes(node, configOnly) {
						hasValid = true
						break
					}
				}
				if !hasValid {
					continue // skip modules without valid fields
				}

				modStructName := toCamelCaseTitle(mod.Name) + treeType
				modFieldName := toCamelCaseTitle(mod.Name)
				xmlTag := fmt.Sprintf(" xml:\"%s,omitempty\"", mod.Name)
				if mod.Namespace != "" {
					xmlTag = fmt.Sprintf(" xml:\"%s %s,omitempty\"", mod.Namespace, mod.Name)
				}
				if _, err := fmt.Fprintf(w, "\t%s *%s `json:\"%s,omitempty\"%s`\n", modFieldName, modStructName, mod.Name, xmlTag); err != nil {
					return fmt.Errorf("write err: %w", err)
				}
			}
			if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
				return fmt.Errorf("write err: %w", err)
			}

			// Validate method for root Device
			if _, err := fmt.Fprintf(w, "// Validate verifies the constraints of %s%s.\nfunc (s *%s%s) Validate() error {\n", g.Options.RootName, treeType, g.Options.RootName, treeType); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
			for _, mod := range modules {
				hasValid := false
				for _, node := range mod.Nodes {
					if g.hasValidNodes(node, configOnly) {
						hasValid = true
						break
					}
				}
				if !hasValid {
					continue
				}
				modFieldName := toCamelCaseTitle(mod.Name)
				if _, err := fmt.Fprintf(w, "\tif s.%s != nil {\n\t\tif err := s.%s.Validate(); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", modFieldName, modFieldName); err != nil {
					return fmt.Errorf("write err: %w", err)
				}
			}
			if _, err := fmt.Fprintf(w, "\treturn nil\n}\n\n"); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		}

		// Now generate each Module Struct
		for _, mod := range modules {
			hasValid := false
			for _, node := range mod.Nodes {
				if g.hasValidNodes(node, configOnly) {
					hasValid = true
					break
				}
			}
			if !hasValid {
				continue
			}

			modStructName := toCamelCaseTitle(mod.Name) + treeType
			if visited[modStructName] {
				continue
			}
			visited[modStructName] = true

			if _, err := fmt.Fprintf(w, "// %s represents the YANG module %s.\n", modStructName, mod.Name); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
			if _, err := fmt.Fprintf(w, "type %s struct {\n", modStructName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}

			var modTopNodes []schema.Node
			for _, name := range getOrderedChildNames(mod.Nodes) {
				child := mod.Nodes[name]
				if !g.hasValidNodes(child, configOnly) {
					continue
				}
				modTopNodes = append(modTopNodes, child)
			}

			prefix := toCamelCaseTitle(mod.Name)
			for _, node := range modTopNodes {
				// Handle 'Validate' collision when generating the struct fields directly
				fieldName := toCamelCaseTitle(node.Name())
				if fieldName == "Validate" {
					fieldName = "ValidateField"
				}
				goType := "*string" // Default placeholder
				switch n := node.(type) {
				case *schema.Leaf:
					goType = mapYANGTypeToGo(n.Type.Name)
				case *schema.LeafList:
					goType = "[]" + mapYANGTypeToGo(n.Type.Name)
				case *schema.Container:
					goType = "*" + prefix + toCamelCaseTitle(n.Name()) + treeType
				case *schema.List:
					goType = "[]*" + prefix + toCamelCaseTitle(n.Name()) + treeType
				}
				xmlTag := fmt.Sprintf(" xml:\"%s,omitempty\"", node.Name())
				if mod.Namespace != "" {
					xmlTag = fmt.Sprintf(" xml:\"%s %s,omitempty\"", mod.Namespace, node.Name())
				}
				if _, err := fmt.Fprintf(w, "\t%s %s `json:\"%s,omitempty\"%s`\n", fieldName, goType, node.Name(), xmlTag); err != nil {
					return fmt.Errorf("write err: %w", err)
				}
			}
			if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
				return fmt.Errorf("write err: %w", err)
			}

			if err := g.generateValidationChecks(modStructName, modTopNodes, w); err != nil {
				return err
			}
			if g.Options.GenerateGetters {
				if err := g.generateGetters(modStructName, modTopNodes, prefix, treeType, w); err != nil {
					return err
				}
			}
			if g.Options.GenerateSetters {
				if err := g.generateSetters(modStructName, modTopNodes, prefix, treeType, w); err != nil {
					return fmt.Errorf("generateSetters err: %w", err)
				}
			}
			if g.Options.GeneratePopulateDefault {
				if err := g.generatePopulateDefault(modStructName, modTopNodes, prefix, treeType, w); err != nil {
					return fmt.Errorf("generatePopulateDefault err: %w", err)
				}
			}
			if g.Options.GenerateOrderedMaps {
				if err := g.generateSorts(modStructName, modTopNodes, w); err != nil {
					return err
				}
			}

			for _, node := range modTopNodes {
				if err := g.generateNode(node, w, visited, prefix, treeType, mod.Namespace, configOnly); err != nil {
					return err
				}
			}
		}
	}

	return nil
}

func (g *GoGenerator) generateNode(node schema.Node, w io.Writer, visited map[string]bool, prefix, suffix, namespace string, configOnly bool) error {
	switch n := node.(type) {
	case *schema.Container:
		return g.generateStruct(n.Name(), n.Description, n.Children, "container", w, visited, prefix, suffix, namespace, configOnly)
	case *schema.List:
		return g.generateStruct(n.Name()+"Entry", n.Description, n.Children, "list", w, visited, prefix, suffix, namespace, configOnly)
	case *schema.Leaf:
		if n.Type.Name == "union" && len(n.Type.Members) > 0 {
			ut := unionGoTypeName(prefix, n.Name())
			if !visited[ut] {
				visited[ut] = true
				if err := g.generateUnionStruct(ut, n.Type.Members, w); err != nil {
					return err
				}
			}
		} else if n.Type.Name == "bits" && len(n.Type.Bits) > 0 {
			bt := bitsGoTypeName(prefix, n.Name())
			if n.Type.TypedefName != "" {
				bt = typedefGoTypeName(prefix, n.Type.TypedefName)
			}
			if !visited[bt] {
				visited[bt] = true
				if err := g.generateBitsType(bt, n.Type.Bits, w); err != nil {
					return err
				}
			}
		} else if n.Type.Name == "enumeration" && len(n.Type.Enums) > 0 {
			et := enumGoTypeName(prefix, n.Name())
			if n.Type.TypedefName != "" {
				et = typedefGoTypeName(prefix, n.Type.TypedefName)
			}
			if !visited[et] {
				visited[et] = true
				if err := g.generateEnumType(et, n.Type.Enums, w); err != nil {
					return err
				}
			}
		} else if n.Type.TypedefName != "" && isScalarType(n.Type.Name) {
			tt := typedefGoTypeName(prefix, n.Type.TypedefName)
			if !visited[tt] {
				visited[tt] = true
				if err := g.generateTypedef(tt, mapYANGTypeToGoBase(n.Type.Name), w); err != nil {
					return err
				}
			}
		}
	case *schema.LeafList:
		if n.Type.Name == "union" && len(n.Type.Members) > 0 {
			ut := unionGoTypeName(prefix, n.Name())
			if !visited[ut] {
				visited[ut] = true
				if err := g.generateUnionStruct(ut, n.Type.Members, w); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func (g *GoGenerator) generateStruct(name string, description *string, children map[string]schema.Node, kind string, w io.Writer, visited map[string]bool, prefix, suffix, namespace string, configOnly bool) error {
	structName := prefix + toCamelCaseTitle(name) + suffix
	if visited[structName] {
		return nil
	}
	visited[structName] = true

	// Separate non-choice flat nodes from choice nodes
	nonChoiceNodes := getNonChoiceFlatNodes(children)
	choices := getChoiceNodes(children)

	var validNonChoiceNodes []schema.Node
	for _, child := range nonChoiceNodes {
		if g.hasValidNodes(child, configOnly) {
			validNonChoiceNodes = append(validNonChoiceNodes, child)
		}
	}

	// Filter valid choices (those with at least one case with valid nodes)
	var validChoices []*schema.Choice
	for _, ch := range choices {
		hasValid := false
		for _, caseName := range getOrderedChildNames(ch.Children) {
			caseNode := ch.Children[caseName]
			caseFlat := getFlatDataNodes(caseNode.GetChildren())
			for _, cf := range caseFlat {
				if g.hasValidNodes(cf, configOnly) {
					hasValid = true
					break
				}
			}
			if hasValid {
				break
			}
		}
		if hasValid {
			validChoices = append(validChoices, ch)
		}
	}

	if len(validNonChoiceNodes) == 0 && len(validChoices) == 0 {
		return nil
	}

	// Generate choice interface + case struct types before the parent struct
	for _, ch := range validChoices {
		if err := g.generateChoiceTypes(structName, ch, w, prefix, suffix, namespace, configOnly); err != nil {
			return err
		}
	}

	if g.Options.AddAnnotations && description != nil && *description != "" {
		for line := range strings.SplitSeq(strings.TrimSpace(*description), "\n") {
			if _, err := fmt.Fprintf(w, "// %s\n", strings.TrimSpace(line)); err != nil {
				return err
			}
		}
	}
	if _, err := fmt.Fprintf(w, "// %s represents the YANG %s %s.\n", structName, kind, name); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	if _, err := fmt.Fprintf(w, "type %s struct {\n", structName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	// Regular (non-choice) fields
	for _, child := range validNonChoiceNodes {
		if err := g.generateField(child, w, prefix, suffix, namespace); err != nil {
			return err
		}
	}

	// Choice interface fields
	for _, ch := range validChoices {
		choiceInterfaceName := choiceGoTypeName(structName, ch.Name())
		fieldName := toCamelCaseTitle(ch.Name())
		if _, err := fmt.Fprintf(w, "\t%s %s `json:\"-\"`\n", fieldName, choiceInterfaceName); err != nil {
			return fmt.Errorf("write err: %w", err)
		}
	}

	if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	// Generate custom MarshalJSON/UnmarshalJSON if there are choices
	if len(validChoices) > 0 {
		if err := g.generateChoiceMarshalJSON(structName, validChoices, w); err != nil {
			return err
		}
		if err := g.generateChoiceUnmarshalJSON(structName, validChoices, w); err != nil {
			return err
		}
	}

	// Only validate non-choice fields; choice case fields are in their own structs
	if err := g.generateValidationChecks(structName, validNonChoiceNodes, w); err != nil {
		return err
	}
	if g.Options.GenerateGetters {
		if err := g.generateGetters(structName, validNonChoiceNodes, prefix, suffix, w); err != nil {
			return fmt.Errorf("generateGetters err: %w", err)
		}
	}
	if g.Options.GenerateSetters {
		if err := g.generateSetters(structName, validNonChoiceNodes, prefix, suffix, w); err != nil {
			return fmt.Errorf("generateSetters err: %w", err)
		}
	}
	if g.Options.GeneratePopulateDefault {
		if err := g.generatePopulateDefault(structName, validNonChoiceNodes, prefix, suffix, w); err != nil {
			return fmt.Errorf("generatePopulateDefault err: %w", err)
		}
	}
	if g.Options.GenerateOrderedMaps {
		if err := g.generateSorts(structName, validNonChoiceNodes, w); err != nil {
			return err
		}
	}

	// Recurse for nested structs in non-choice nodes
	for _, child := range validNonChoiceNodes {
		if err := g.generateNode(child, w, visited, prefix, suffix, namespace, configOnly); err != nil {
			return err
		}
	}
	// Recurse for nested structs inside choice cases
	for _, ch := range validChoices {
		for _, caseName := range getOrderedChildNames(ch.Children) {
			caseNode := ch.Children[caseName]
			for _, caseChild := range getFlatDataNodes(caseNode.GetChildren()) {
				if g.hasValidNodes(caseChild, configOnly) {
					if err := g.generateNode(caseChild, w, visited, prefix, suffix, namespace, configOnly); err != nil {
						return err
					}
				}
			}
		}
	}
	return nil
}

func (g *GoGenerator) generateField(node schema.Node, w io.Writer, prefix, suffix, namespace string) error {
	fieldName := toCamelCaseTitle(node.Name())
	if fieldName == "Validate" {
		fieldName = "ValidateField"
	}
	goType := "*string" // Default placeholder

	switch n := node.(type) {
	case *schema.Leaf:
		if n.Type.Name == "union" && len(n.Type.Members) > 0 {
			goType = "*" + unionGoTypeName(prefix, n.Name())
		} else if n.Type.Name == "bits" && len(n.Type.Bits) > 0 {
			if n.Type.TypedefName != "" {
				goType = "*" + typedefGoTypeName(prefix, n.Type.TypedefName)
			} else {
				goType = "*" + bitsGoTypeName(prefix, n.Name())
			}
		} else if n.Type.Name == "enumeration" && len(n.Type.Enums) > 0 {
			if n.Type.TypedefName != "" {
				goType = "*" + typedefGoTypeName(prefix, n.Type.TypedefName)
			} else {
				goType = "*" + enumGoTypeName(prefix, n.Name())
			}
		} else if n.Type.TypedefName != "" && isScalarType(n.Type.Name) {
			goType = "*" + typedefGoTypeName(prefix, n.Type.TypedefName)
		} else {
			goType = mapYANGTypeToGo(n.Type.Name)
		}
	case *schema.LeafList:
		if n.Type.Name == "union" && len(n.Type.Members) > 0 {
			goType = "[]" + unionGoTypeName(prefix, n.Name())
		} else {
			goType = "[]" + mapYANGTypeToGo(n.Type.Name)
		}
	case *schema.Container:
		goType = "*" + prefix + toCamelCaseTitle(n.Name()) + suffix
	case *schema.List:
		goType = "[]*" + prefix + toCamelCaseTitle(n.Name()) + "Entry" + suffix
	}

	xmlTag := fmt.Sprintf(" xml:\"%s,omitempty\"", node.Name())
	if namespace != "" {
		xmlTag = fmt.Sprintf(" xml:\"%s %s,omitempty\"", namespace, node.Name())
	}

	moduleName := node.GetBase().ModuleName
	yangTag := fmt.Sprintf(" yang:\"%s:%s\"", moduleName, node.Name())

	if g.Options.AddAnnotations && node.GetBase().Description != nil && *node.GetBase().Description != "" {
		for line := range strings.SplitSeq(strings.TrimSpace(*node.GetBase().Description), "\n") {
			if _, err := fmt.Fprintf(w, "\t// %s\n", strings.TrimSpace(line)); err != nil {
				return err
			}
		}
	}

	if _, err := fmt.Fprintf(w, "\t%s %s `json:\"%s,omitempty\"%s%s`\n", fieldName, goType, node.Name(), xmlTag, yangTag); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	return nil
}

func toCamelCaseTitle(s string) string {
	s = strings.ReplaceAll(s, ".", "_")
	parts := strings.Split(s, "-")
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func mapYANGTypeToGo(yangType string) string {
	switch yangType {
	case "int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64":
		return "*" + yangType
	case "boolean":
		return "*bool"
	case "decimal64":
		return "*float64"
	case "empty":
		return "*bool"
	case "binary":
		return "[]byte"
	case "bits":
		// Fallback when bits has no named members — treat as string
		return "*string"
	case "enumeration":
		// Fallback when enumeration has no named values — treat as string
		return "*string"
	default:
		return "*string"
	}
}

// bitsGoTypeName generates the Go type name for a YANG bits type.
func bitsGoTypeName(prefix, nodeName string) string {
	return prefix + toCamelCaseTitle(nodeName) + "Bits"
}

// enumGoTypeName generates the Go type name for a YANG enumeration type.
func enumGoTypeName(prefix, nodeName string) string {
	return prefix + toCamelCaseTitle(nodeName) + "Enum"
}

// typedefGoTypeName generates the Go type name for a YANG typedef.
func typedefGoTypeName(prefix, typedefName string) string {
	return prefix + toCamelCaseTitle(typedefName)
}

// isScalarType returns true for built-in YANG types that map to Go scalar types.
func isScalarType(name string) bool {
	switch name {
	case "int8", "int16", "int32", "int64",
		"uint8", "uint16", "uint32", "uint64",
		"boolean", "decimal64", "string", "binary", "empty":
		return true
	default:
		return false
	}
}

// mapYANGTypeToGoBase returns the Go base type name without pointer wrapper.
func mapYANGTypeToGoBase(yangType string) string {
	switch yangType {
	case "int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64":
		return yangType
	case "boolean":
		return "bool"
	case "decimal64":
		return "float64"
	case "empty":
		return "bool"
	case "binary":
		return "[]byte"
	case "string":
		return "string"
	default:
		return "string"
	}
}

func (g *GoGenerator) generateValidationChecks(structName string, flatNodes []schema.Node, w io.Writer) error {
	if _, err := fmt.Fprintf(w, "// Validate verifies the constraints of %s.\n", structName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	if _, err := fmt.Fprintf(w, "func (s *%s) Validate() error {\n", structName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	for _, node := range flatNodes {
		fieldName := toCamelCaseTitle(node.Name())
		if (strings.HasSuffix(structName, "Config") || strings.HasSuffix(structName, "State")) && fieldName == "Validate" {
			fieldName = "ValidateField"
		}
		// In case any internal field is natively named Validate, we handle it during field generation
		if fieldName == "Validate" {
			fieldName = "ValidateField"
		}

		switch n := node.(type) {
		case *schema.Container:
			if _, err := fmt.Fprintf(w, "\tif s.%s != nil {\n\t\tif err := s.%s.Validate(); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", fieldName, fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		case *schema.List:
			if _, err := fmt.Fprintf(w, "\tfor _, item := range s.%s {\n\t\tif item != nil {\n\t\t\tif err := item.Validate(); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n\t\t}\n\t}\n", fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		case *schema.Leaf:
			if err := g.writeValidationRule(w, fieldName, "s."+fieldName, n.Type); err != nil {
				return err
			}
		case *schema.LeafList:
			if len(n.Type.Length) > 0 || len(n.Type.Range) > 0 || len(n.Type.Pattern) > 0 {
				if _, err := fmt.Fprintf(w, "\tfor _, item := range s.%s {\n", fieldName); err != nil {
					return fmt.Errorf("write err: %w", err)
				}
				if err := g.writeValidationRule(w, fieldName, "item", n.Type); err != nil {
					return err
				}
				if _, err := fmt.Fprintf(w, "\t}\n"); err != nil {
					return fmt.Errorf("write err: %w", err)
				}
			}
		}
	}

	if _, err := fmt.Fprintf(w, "\treturn nil\n}\n\n"); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	return nil
}

// getOrderedChildNames returns the names of children sorted by their schema definition order.
func getOrderedChildNames(children map[string]schema.Node) []string {
	type nameOrder struct {
		name  string
		order int
	}
	list := make([]nameOrder, 0, len(children))
	for name, node := range children {
		list = append(list, nameOrder{
			name:  name,
			order: node.GetBase().Order,
		})
	}
	sort.Slice(list, func(i, j int) bool {
		return list[i].order < list[j].order
	})

	names := make([]string, len(list))
	for i, item := range list {
		names[i] = item.name
	}
	return names
}

// getFlatDataNodes recurses into Choice and Case nodes to extract the actual
// data tree children that participate in JSON/XML representations natively.
func getFlatDataNodes(nodes map[string]schema.Node) []schema.Node {
	var result []schema.Node
	seen := make(map[string]bool)

	var walk func(ns map[string]schema.Node)
	walk = func(ns map[string]schema.Node) {
		for _, name := range getOrderedChildNames(ns) {
			node := ns[name]
			switch n := node.(type) {
			case *schema.Choice:
				for _, caseName := range getOrderedChildNames(n.Children) {
					caseNode := n.Children[caseName]
					walk(caseNode.GetChildren())
				}
			case *schema.Case:
				walk(n.Children)
			default:
				if !seen[node.Name()] {
					seen[node.Name()] = true
					result = append(result, node)
				}
			}
		}
	}
	walk(nodes)
	return result
}

// getChoiceNodes returns only the Choice nodes from a children map, in order.
func getChoiceNodes(children map[string]schema.Node) []*schema.Choice {
	var choices []*schema.Choice
	for _, name := range getOrderedChildNames(children) {
		if c, ok := children[name].(*schema.Choice); ok {
			choices = append(choices, c)
		}
	}
	return choices
}

// getNonChoiceFlatNodes returns flat data nodes excluding any that live inside choices.
func getNonChoiceFlatNodes(nodes map[string]schema.Node) []schema.Node {
	var result []schema.Node
	seen := make(map[string]bool)
	for _, name := range getOrderedChildNames(nodes) {
		node := nodes[name]
		switch node.(type) {
		case *schema.Choice:
			// Skip — handled separately
		case *schema.Case:
			// Should not appear at top level, but skip
		default:
			if !seen[node.Name()] {
				seen[node.Name()] = true
				result = append(result, node)
			}
		}
	}
	return result
}

