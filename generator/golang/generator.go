// generateUnionStruct emits a union wrapper struct with one optional field per
// member type (in YANG declaration order) and the corresponding UnmarshalJSON /
// MarshalJSON methods that enforce RFC 7950 §7.4 ordered matching.
func (g *GoGenerator) generateUnionStruct(typeName string, members []schema.TypeDefinition, w io.Writer) error {
	// Build per-member field info: field name, Go type, unmarshal snippet.
	type memberInfo struct {
		fieldName string
		goType    string
		ptrType   bool   // true when the Go type is a pointer (*T)
		baseType  string // T without the leading *
	}
	seen := make(map[string]int)
	infos := make([]memberInfo, 0, len(members))
	for _, m := range members {
		goType := mapYANGTypeToGo(m.Name)
		// Derive a unique field name from the YANG type name.
		// Strip any module prefix (e.g. "bbf-qos-t:traffic-class-id" → "traffic-class-id")
		localName := m.Name
		if idx := strings.LastIndex(localName, ":"); idx >= 0 {
			localName = localName[idx+1:]
		}
		base := toCamelCaseTitle(localName)
		if _, exists := seen[base]; exists {
			seen[base]++
			base = fmt.Sprintf("%s%d", base, seen[base])
		} else {
			seen[base] = 0
		}
		isPtr := strings.HasPrefix(goType, "*")
		baseType := strings.TrimPrefix(goType, "*")
		infos = append(infos, memberInfo{
			fieldName: base,
			goType:    goType,
			ptrType:   isPtr,
			baseType:  baseType,
		})
	}

	// --- struct definition ---
	if _, err := fmt.Fprintf(w, "// %s represents the YANG union type with %d member(s).\ntype %s struct {\n", typeName, len(members), typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	for _, info := range infos {
		if _, err := fmt.Fprintf(w, "\t%s %s\n", info.fieldName, info.goType); err != nil {
			return fmt.Errorf("write err: %w", err)
		}
	}
	if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	// --- UnmarshalJSON: try members in declaration order (RFC 7950 §7.4) ---
	if _, err := fmt.Fprintf(w, "// UnmarshalJSON implements json.Unmarshaler for %s.\n// Members are tried in YANG declaration order per RFC 7950 §7.4.\nfunc (u *%s) UnmarshalJSON(b []byte) error {\n", typeName, typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	for _, info := range infos {
		if info.ptrType {
			// pointer type: unmarshal into a value then take its address
			if _, err := fmt.Fprintf(w,
				"\t{ var v %s\n\t  if err := json.Unmarshal(b, &v); err == nil { u.%s = &v; return nil } }\n",
				info.baseType, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		} else {
			// non-pointer (e.g. []byte / binary)
			if _, err := fmt.Fprintf(w,
				"\t{ var v %s\n\t  if err := json.Unmarshal(b, &v); err == nil { u.%s = v; return nil } }\n",
				info.goType, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		}
	}
	if _, err := fmt.Fprintf(w, "\treturn fmt.Errorf(\"%s: no union member matched %%s\", string(b))\n}\n\n", typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	// --- MarshalJSON: serialize whichever field is set ---
	if _, err := fmt.Fprintf(w, "// MarshalJSON implements json.Marshaler for %s.\nfunc (u %s) MarshalJSON() ([]byte, error) {\n", typeName, typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	for _, info := range infos {
		if info.ptrType {
			if _, err := fmt.Fprintf(w, "\tif u.%s != nil { return json.Marshal(u.%s) }\n", info.fieldName, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		} else {
			// binary / slice: check len
			if _, err := fmt.Fprintf(w, "\tif len(u.%s) > 0 { return json.Marshal(u.%s) }\n", info.fieldName, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		}
	}
	if _, err := fmt.Fprintf(w, "\treturn []byte(\"null\"), nil\n}\n\n"); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	// --- UnmarshalXML: try members in declaration order (RFC 7950 §7.4) ---
	if _, err := fmt.Fprintf(w,
		"// UnmarshalXML implements xml.Unmarshaler for %s.\nfunc (u *%s) UnmarshalXML(d *xml.Decoder, start xml.StartElement) error {\n"+
			"\tvar raw string\n\tif err := d.DecodeElement(&raw, &start); err != nil {\n\t\treturn err\n\t}\n"+
			"\tb := []byte(`\"` + raw + `\"`)\n",
		typeName, typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	for _, info := range infos {
		if info.ptrType {
			if _, err := fmt.Fprintf(w,
				"\t{ var v %s\n\t  if err := json.Unmarshal(b, &v); err == nil { u.%s = &v; return nil } }\n",
				info.baseType, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		} else {
			if _, err := fmt.Fprintf(w,
				"\t{ var v %s\n\t  if err := json.Unmarshal(b, &v); err == nil { u.%s = v; return nil } }\n",
				info.goType, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		}
	}
	if _, err := fmt.Fprintf(w, "\treturn fmt.Errorf(\"%s: no union member matched %%s\", raw)\n}\n\n", typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	// --- MarshalXML: serialize whichever field is set ---
	if _, err := fmt.Fprintf(w,
		"// MarshalXML implements xml.Marshaler for %s.\nfunc (u %s) MarshalXML(e *xml.Encoder, start xml.StartElement) error {\n",
		typeName, typeName); err != nil {
		return fmt.Errorf("write err: %w", err)
	}
	for _, info := range infos {
		if info.ptrType {
			if _, err := fmt.Fprintf(w,
				"\tif u.%s != nil { return e.EncodeElement(*u.%s, start) }\n",
				info.fieldName, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		} else {
			if _, err := fmt.Fprintf(w,
				"\tif len(u.%s) > 0 { return e.EncodeElement(u.%s, start) }\n",
				info.fieldName, info.fieldName); err != nil {
				return fmt.Errorf("write err: %w", err)
			}
		}
	}
	if _, err := fmt.Fprintf(w, "\treturn nil\n}\n\n"); err != nil {
		return fmt.Errorf("write err: %w", err)
	}

	return nil
}

func (g *GoGenerator) writeValidationRule(w io.Writer, fieldName, ptrExpr string, typ schema.TypeDefinition) error {
	valExpr := "*" + ptrExpr
	if typ.Name == "binary" {
		valExpr = ptrExpr // []byte is not a pointer
	}

	// When the type is a typedef, cast to the base Go type for
	// constraint functions that expect primitive types.
	if typ.TypedefName != "" && isScalarType(typ.Name) {
		baseType := mapYANGTypeToGoBase(typ.Name)
		valExpr = baseType + "(" + valExpr + ")"
	}

	if len(typ.Length) > 0 {
		cond := buildLengthCondition(valExpr, typ.Name, typ.Length)
		if cond != "" {
			if _, err := fmt.Fprintf(w, "\tif %s != nil {\n\t\tif !(%s) {\n\t\t\treturn fmt.Errorf(\"%%s length out of range\", %q)\n\t\t}\n\t}\n", ptrExpr, cond, fieldName); err != nil {
				return err
			}
		}
	}
	if len(typ.Range) > 0 {
		cond := buildRangeCondition(valExpr, typ.Range)
		if cond != "" {
			if _, err := fmt.Fprintf(w, "\tif %s != nil {\n\t\tif !(%s) {\n\t\t\treturn fmt.Errorf(\"%%s value out of range\", %q)\n\t\t}\n\t}\n", ptrExpr, cond, fieldName); err != nil {
				return err
			}
		}
	}
	if len(typ.Pattern) > 0 {
		valStr := valExpr
		if typ.Name == "binary" {
			valStr = "string(" + valExpr + ")"
		}
		for _, pat := range typ.Pattern {
			if _, err := fmt.Fprintf(w, "\tif %s != nil {\n\t\tmatched, _ := regexp.MatchString(%q, %s)\n\t\tif !matched {\n\t\t\treturn fmt.Errorf(\"%%s does not match pattern\", %q)\n\t\t}\n\t}\n", ptrExpr, pat, valStr, fieldName); err != nil {
				return err
			}
		}
	}
	return nil
}

func buildLengthCondition(valExpr, yangType string, lengths []string) string {
	lengthFunc := "utf8.RuneCountInString(" + valExpr + ")"
	if yangType == "binary" {
		lengthFunc = "len(" + valExpr + ")"
	}
	return buildBoundsCondition(lengthFunc, lengths)
}

func buildRangeCondition(valExpr string, ranges []string) string {
	return buildBoundsCondition(valExpr, ranges)
}

func buildBoundsCondition(valExpr string, boundsList []string) string {
	var conditions []string
	for _, b := range boundsList {
		var partConds []string
		for p := range strings.SplitSeq(b, "|") {
			p = strings.TrimSpace(p)
			if strings.Contains(p, "..") {
				bounds := strings.Split(p, "..")
				minStr := strings.TrimSpace(bounds[0])
				maxStr := strings.TrimSpace(bounds[1])
				var minCond, maxCond string
				if minStr != "min" && minStr != "max" {
					minCond = fmt.Sprintf("%s >= %s", valExpr, minStr)
				}
				if maxStr != "max" && maxStr != "min" {
					maxCond = fmt.Sprintf("%s <= %s", valExpr, maxStr)
				}
				if minCond != "" && maxCond != "" {
					partConds = append(partConds, fmt.Sprintf("%s && %s", minCond, maxCond))
				} else if minCond != "" {
					partConds = append(partConds, minCond)
				} else if maxCond != "" {
					partConds = append(partConds, maxCond)
				}
			} else {
				if p != "min" && p != "max" {
					partConds = append(partConds, fmt.Sprintf("%s == %s", valExpr, p))
				}
			}
		}
		if len(partConds) > 0 {
			conditions = append(conditions, strings.Join(partConds, " || "))
		}
	}
	if len(conditions) == 0 {
		return ""
	}
	if len(conditions) > 1 {
		for i, c := range conditions {
			conditions[i] = fmt.Sprintf("(%s)", c)
		}
	}
	return strings.Join(conditions, " && ")
}

// generateGetters generates safe nil-checking accessor methods for struct fields.
func (g *GoGenerator) generateGetters(structName string, nodes []schema.Node, prefix, suffix string, w io.Writer) error {
	for _, node := range nodes {
		fieldName := toCamelCaseTitle(node.Name())
		if fieldName == "Validate" {
			fieldName = "ValidateField"
		}

		goType, isPtr, isContainer := g.resolveFieldTypeInfo(node, prefix, suffix)

		// If it's a container or list, we return the pointer/slice/map directly.
		// If it's a primitive leaf pointer, we return the value type.
		returnType := goType
		if isPtr && !isContainer {
			returnType = strings.TrimPrefix(goType, "*")
		}

		if _, err := fmt.Fprintf(w, "// Get%s retrieves the value of the field %s from its parent, returning its default or zero value if unset.\n", fieldName, fieldName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "func (s *%s) Get%s() %s {\n", structName, fieldName, returnType); err != nil {
			return err
		}

		if isPtr && !isContainer {
			// Union is an interface
			if strings.Contains(returnType, "Union") {
				if _, err := fmt.Fprintf(w, "\tif s == nil || s.%s == nil {\n\t\treturn nil\n\t}\n\treturn s.%s\n}\n\n", fieldName, fieldName); err != nil {
					return err
				}
			} else {
				if _, err := fmt.Fprintf(w, "\tif s == nil || s.%s == nil {\n\t\tvar zero %s\n\t\treturn zero\n\t}\n\treturn *s.%s\n}\n\n", fieldName, returnType, fieldName); err != nil {
					return err
				}
			}
		} else {
			// slices, maps, containers -> return directly with nil check
			if _, err := fmt.Fprintf(w, "\tif s == nil {\n\t\tvar zero %s\n\t\treturn zero\n\t}\n\treturn s.%s\n}\n\n", returnType, fieldName); err != nil {
				return err
			}
		}
	}
	return nil
}

// resolveFieldTypeInfo reconstructs the Go type of a node exactly as it's emitted in the struct fields.
func (g *GoGenerator) resolveFieldTypeInfo(node schema.Node, prefix, suffix string) (goType string, isPtr, isContainer bool) {
	switch n := node.(type) {
	case *schema.Leaf:
		if n.Type.Name == "union" && len(n.Type.Members) > 0 {
			goType = unionGoTypeName(prefix, n.Name())
			isPtr = true // For unions, we usually store as interface, effectively a pointer
		} else {
			goType = mapYANGTypeToGo(n.Type.Name)
			if strings.HasPrefix(goType, "*") {
				isPtr = true
			}
		}
	case *schema.LeafList:
		if n.Type.Name == "union" && len(n.Type.Members) > 0 {
			goType = "[]" + unionGoTypeName(prefix, n.Name())
		} else {
			goType = "[]" + mapYANGTypeToGo(n.Type.Name)
		}
	case *schema.Container:
		goType = "*" + prefix + toCamelCaseTitle(n.Name()) + suffix
		isPtr = true
		isContainer = true
	case *schema.List:
		goType = "[]*" + prefix + toCamelCaseTitle(n.Name()) + "Entry" + suffix
		isContainer = true
	}
	return goType, isPtr, isContainer
}

// generateSetters generates setter methods for struct fields.
func (g *GoGenerator) generateSetters(structName string, nodes []schema.Node, prefix, suffix string, w io.Writer) error {
	for _, node := range nodes {
		fieldName := toCamelCaseTitle(node.Name())
		if fieldName == "Validate" {
			fieldName = "ValidateField"
		}

		goType, isPtr, isContainer := g.resolveFieldTypeInfo(node, prefix, suffix)

		// Setters for pointers (leaves) usually take the base value, and the setter wraps it in a pointer.
		// For slices, maps, containers, they take the pointer/slice/map directly.
		argType := goType
		if isPtr && !isContainer {
			argType = strings.TrimPrefix(goType, "*")
		}

		if _, err := fmt.Fprintf(w, "// Set%s sets the value of the field %s.\n", fieldName, fieldName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "func (s *%s) Set%s(v %s) {\n", structName, fieldName, argType); err != nil {
			return err
		}

		if isPtr && !isContainer && !strings.Contains(argType, "Union") {
			if _, err := fmt.Fprintf(w, "\ts.%s = &v\n}\n\n", fieldName); err != nil {
				return err
			}
		} else {
			if _, err := fmt.Fprintf(w, "\ts.%s = v\n}\n\n", fieldName); err != nil {
				return err
			}
		}
	}
	return nil
}

// generatePopulateDefault generates a method that populates nil fields with their YANG default values.
func (g *GoGenerator) generatePopulateDefault(structName string, nodes []schema.Node, prefix, suffix string, w io.Writer) error {
	var body bytes.Buffer
	hasDefaults := false

	for _, node := range nodes {
		fieldName := toCamelCaseTitle(node.Name())
		if fieldName == "Validate" {
			fieldName = "ValidateField"
		}

		switch n := node.(type) {
		case *schema.Leaf:
			if n.Default != nil {
				goType, _, _ := g.resolveFieldTypeInfo(node, prefix, suffix)
				baseType := strings.TrimPrefix(goType, "*")

				// parse the default string into the go type
				if strings.Contains(baseType, "Union") {
					continue
				}

				valStr := ""
				switch baseType {
				case "string":
					valStr = fmt.Sprintf(`"%s"`, *n.Default)
				case "bool":
					valStr = *n.Default
				default:
					valStr = fmt.Sprintf("%s(%s)", baseType, *n.Default)
				}

				fmt.Fprintf(&body, "\tif s.%s == nil {\n\t\tvar v %s = %s\n\t\ts.%s = &v\n\t}\n", fieldName, baseType, valStr, fieldName)
				hasDefaults = true
			}
		}
	}

	if hasDefaults {
		if _, err := fmt.Fprintf(w, "// PopulateDefaults recursively populates nil fields in %s with default values.\n", structName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "func (s *%s) PopulateDefaults() {\n%s}\n\n", structName, body.String()); err != nil {
			return err
		}
	}
	return nil
}

// generateSorts generates methods to state if a list or leaf-list is ordered, and by what semantics.
func (g *GoGenerator) generateSorts(structName string, nodes []schema.Node, w io.Writer) error {
	for _, node := range nodes {
		fieldName := toCamelCaseTitle(node.Name())
		if fieldName == "Validate" {
			fieldName = "ValidateField"
		}

		orderedBy := "system"
		switch n := node.(type) {
		case *schema.List:
			if n.OrderedBy != nil {
				orderedBy = *n.OrderedBy
			}
		case *schema.LeafList:
			if n.OrderedBy != nil {
				orderedBy = *n.OrderedBy
			}
		default:
			continue
		}

		isOrdered := orderedBy == "user"

		if _, err := fmt.Fprintf(w, "// IsOrdered%s returns true if the %s slice is ordered-by user.\n", fieldName, fieldName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "func (s *%s) IsOrdered%s() bool {\n", structName, fieldName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "\treturn %v\n", isOrdered); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
			return err
		}

		if _, err := fmt.Fprintf(w, "// Order%s returns the ordered-by semantics of the %s slice.\n", fieldName, fieldName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "func (s *%s) Order%s() string {\n", structName, fieldName); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "\treturn \"%s\"\n", orderedBy); err != nil {
			return err
		}
		if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
			return err
		}
	}
	return nil
}

// generateBitsType generates a named uint64 type for a YANG bits leaf,
// with iota constants, name/value maps, bitwise helpers, and JSON marshaling.
func (g *GoGenerator) generateBitsType(typeName string, bits []string, w io.Writer) error {
	// Type declaration
	if _, err := fmt.Fprintf(w, "// %s represents the YANG bits type with %d bit(s).\ntype %s uint64\n\n", typeName, len(bits), typeName); err != nil {
		return err
	}

	// Constants using iota
	if _, err := fmt.Fprintf(w, "const (\n"); err != nil {
		return err
	}
	for i, bit := range bits {
		constName := typeName + toCamelCaseTitle(bit)
		if i == 0 {
			if _, err := fmt.Fprintf(w, "\t%s %s = 1 << iota\n", constName, typeName); err != nil {
				return err
			}
		} else {
			if _, err := fmt.Fprintf(w, "\t%s\n", constName); err != nil {
				return err
			}
		}
	}
	if _, err := fmt.Fprintf(w, ")\n\n"); err != nil {
		return err
	}

	// Lowercase variable name for maps
	lowerName := strings.ToLower(typeName[:1]) + typeName[1:]

	// Name to value map
	if _, err := fmt.Fprintf(w, "var %sNameMap = map[string]%s{\n", lowerName, typeName); err != nil {
		return err
	}
	for _, bit := range bits {
		constName := typeName + toCamelCaseTitle(bit)
		if _, err := fmt.Fprintf(w, "\t\"%s\": %s,\n", bit, constName); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
		return err
	}

	// Value to name map
	if _, err := fmt.Fprintf(w, "var %sValueMap = map[%s]string{\n", lowerName, typeName); err != nil {
		return err
	}
	for _, bit := range bits {
		constName := typeName + toCamelCaseTitle(bit)
		if _, err := fmt.Fprintf(w, "\t%s: \"%s\",\n", constName, bit); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
		return err
	}

	// Has method
	if _, err := fmt.Fprintf(w, "// Has returns true if the given bit is set.\nfunc (b %s) Has(flag %s) bool { return b&flag != 0 }\n\n", typeName, typeName); err != nil {
		return err
	}

	// Set method
	if _, err := fmt.Fprintf(w, "// Set returns the bits value with the given flag set.\nfunc (b %s) Set(flag %s) %s { return b | flag }\n\n", typeName, typeName, typeName); err != nil {
		return err
	}

	// Clear method
	if _, err := fmt.Fprintf(w, "// Clear returns the bits value with the given flag cleared.\nfunc (b %s) Clear(flag %s) %s { return b &^ flag }\n\n", typeName, typeName, typeName); err != nil {
		return err
	}

	// String method
	if _, err := fmt.Fprintf(w, "// String returns the space-separated names of all set bits.\nfunc (b %s) String() string {\n\tvar names []string\n\tfor val, name := range %sValueMap {\n\t\tif b&val != 0 {\n\t\t\tnames = append(names, name)\n\t\t}\n\t}\n\treturn strings.Join(names, \" \")\n}\n\n", typeName, lowerName); err != nil {
		return err
	}

	// MarshalJSON
	if _, err := fmt.Fprintf(w, "// MarshalJSON implements json.Marshaler for %s.\n// RFC 7951 §6.7: bits are encoded as a space-separated string of set bit names.\nfunc (b %s) MarshalJSON() ([]byte, error) {\n\treturn json.Marshal(b.String())\n}\n\n", typeName, typeName); err != nil {
		return err
	}

	// UnmarshalJSON
	if _, err := fmt.Fprintf(w, "// UnmarshalJSON implements json.Unmarshaler for %s.\nfunc (b *%s) UnmarshalJSON(data []byte) error {\n\tvar s string\n\tif err := json.Unmarshal(data, &s); err != nil {\n\t\treturn err\n\t}\n\tif s == \"\" {\n\t\t*b = 0\n\t\treturn nil\n\t}\n\tfor name := range strings.SplitSeq(s, \" \") {\n\t\tif val, ok := %sNameMap[name]; ok {\n\t\t\t*b = b.Set(val)\n\t\t} else {\n\t\t\treturn fmt.Errorf(\"unknown bit name %%q for %s\", name)\n\t\t}\n\t}\n\treturn nil\n}\n", typeName, typeName, lowerName, typeName); err != nil {
		return err
	}

	return nil
}

// generateEnumType generates a named uint64 type for a YANG enumeration leaf,
// with iota constants, name/value maps, and JSON marshaling.
func (g *GoGenerator) generateEnumType(typeName string, enums []string, w io.Writer) error {
	// Type declaration
	if _, err := fmt.Fprintf(w, "// %s represents the YANG enumeration type with %d value(s).\ntype %s uint64\n\n", typeName, len(enums), typeName); err != nil {
		return err
	}

	// Constants using iota (sequential, not bit-shifted)
	if _, err := fmt.Fprintf(w, "const (\n"); err != nil {
		return err
	}
	for i, enum := range enums {
		constName := typeName + toCamelCaseTitle(enum)
		if i == 0 {
			if _, err := fmt.Fprintf(w, "\t%s %s = iota\n", constName, typeName); err != nil {
				return err
			}
		} else {
			if _, err := fmt.Fprintf(w, "\t%s\n", constName); err != nil {
				return err
			}
		}
	}
	if _, err := fmt.Fprintf(w, ")\n\n"); err != nil {
		return err
	}

	// Lowercase variable name for maps
	lowerName := strings.ToLower(typeName[:1]) + typeName[1:]

	// Name to value map
	if _, err := fmt.Fprintf(w, "var %sNameMap = map[string]%s{\n", lowerName, typeName); err != nil {
		return err
	}
	for _, enum := range enums {
		constName := typeName + toCamelCaseTitle(enum)
		if _, err := fmt.Fprintf(w, "\t\"%s\": %s,\n", enum, constName); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
		return err
	}

	// Value to name map
	if _, err := fmt.Fprintf(w, "var %sValueMap = map[%s]string{\n", lowerName, typeName); err != nil {
		return err
	}
	for _, enum := range enums {
		constName := typeName + toCamelCaseTitle(enum)
		if _, err := fmt.Fprintf(w, "\t%s: \"%s\",\n", constName, enum); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, "}\n\n"); err != nil {
		return err
	}

	// String method
	if _, err := fmt.Fprintf(w, "// String returns the YANG name of the enum value.\nfunc (e %s) String() string {\n\tif name, ok := %sValueMap[e]; ok {\n\t\treturn name\n\t}\n\treturn fmt.Sprintf(\"%s(%%d)\", uint64(e))\n}\n\n", typeName, lowerName, typeName); err != nil {
		return err
	}

	// MarshalJSON — enum → string value
	if _, err := fmt.Fprintf(w, "// MarshalJSON implements json.Marshaler for %s.\nfunc (e %s) MarshalJSON() ([]byte, error) {\n\treturn json.Marshal(e.String())\n}\n\n", typeName, typeName); err != nil {
		return err
	}

	// UnmarshalJSON — string → enum
	if _, err := fmt.Fprintf(w, "// UnmarshalJSON implements json.Unmarshaler for %s.\nfunc (e *%s) UnmarshalJSON(data []byte) error {\n\tvar s string\n\tif err := json.Unmarshal(data, &s); err != nil {\n\t\treturn err\n\t}\n\tif val, ok := %sNameMap[s]; ok {\n\t\t*e = val\n\t\treturn nil\n\t}\n\treturn fmt.Errorf(\"unknown enum value %%q for %s\", s)\n}\n\n", typeName, typeName, lowerName, typeName); err != nil {
		return err
	}

	return nil
}

